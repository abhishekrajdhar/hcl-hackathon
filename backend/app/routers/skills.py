"""Skill knowledge graph HTTP surface.

Routers stay thin: they validate, delegate to the service, and serialise.
Graph traversal, sequencing and cycle prevention are computed deterministically
in `SkillGraphService` — never generated by a model.
"""

from __future__ import annotations

import uuid

from fastapi import APIRouter, Query, status

from app.core.deps import AdminUser, CurrentUser, PaginationDep, SessionDep
from app.schemas.common import Page
from app.schemas.skill import (
    CycleReport,
    DependentEdgeRead,
    LearningSequenceRequest,
    LearningSequenceResponse,
    PrerequisiteCreate,
    PrerequisiteEdgeRead,
    PrerequisiteRead,
    PrerequisiteTreeResponse,
    PrerequisiteUpdate,
    SkillCategoryCreate,
    SkillCategoryRead,
    SkillCategoryUpdate,
    SkillCreate,
    SkillDependencyAnalysis,
    SkillGraphResponse,
    SkillRead,
    SkillUpdate,
    ValidateOrderRequest,
    ValidateOrderResponse,
)
from app.services.skill_graph_service import SkillGraphService
from app.services.skill_service import SkillCategoryService, SkillService

router = APIRouter(prefix="/skills", tags=["skills"])
categories_router = APIRouter(prefix="/skill-categories", tags=["skills"])
prerequisites_router = APIRouter(prefix="/prerequisites", tags=["skills"])


# --- categories ------------------------------------------------------------
@categories_router.get("", response_model=list[SkillCategoryRead])
async def list_categories(session: SessionDep, _: CurrentUser) -> list[SkillCategoryRead]:
    items = await SkillCategoryService(session).list()
    return [SkillCategoryRead.model_validate(c) for c in items]


@categories_router.post(
    "", response_model=SkillCategoryRead, status_code=status.HTTP_201_CREATED
)
async def create_category(
    payload: SkillCategoryCreate, session: SessionDep, _: AdminUser
) -> SkillCategoryRead:
    return SkillCategoryRead.model_validate(await SkillCategoryService(session).create(payload))


@categories_router.patch("/{category_id}", response_model=SkillCategoryRead)
async def update_category(
    category_id: uuid.UUID, payload: SkillCategoryUpdate, session: SessionDep, _: AdminUser
) -> SkillCategoryRead:
    return SkillCategoryRead.model_validate(
        await SkillCategoryService(session).update(category_id, payload)
    )


@categories_router.delete(
    "/{category_id}", status_code=status.HTTP_204_NO_CONTENT, response_model=None
)
async def delete_category(category_id: uuid.UUID, session: SessionDep, _: AdminUser) -> None:
    await SkillCategoryService(session).delete(category_id)


# --- skills ----------------------------------------------------------------
@router.get("", response_model=Page[SkillRead])
async def list_skills(
    session: SessionDep,
    pagination: PaginationDep,
    _: CurrentUser,
    search: str | None = Query(default=None, min_length=1, max_length=128),
    category_id: uuid.UUID | None = None,
    category: str | None = Query(default=None, description="Filter by category slug"),
    domain: str | None = None,
    min_difficulty: int | None = Query(default=None, ge=1, le=5),
    max_difficulty: int | None = Query(default=None, ge=1, le=5),
    is_active: bool | None = True,
) -> Page[SkillRead]:
    items, total = await SkillService(session).list(
        limit=pagination.limit,
        offset=pagination.offset,
        search=search,
        category_id=category_id,
        category_slug=category,
        domain=domain,
        min_difficulty=min_difficulty,
        max_difficulty=max_difficulty,
        is_active=is_active,
    )
    return Page[SkillRead](
        items=[SkillRead.model_validate(s) for s in items],
        total=total,
        limit=pagination.limit,
        offset=pagination.offset,
    )


@router.post("", response_model=SkillRead, status_code=status.HTTP_201_CREATED)
async def create_skill(payload: SkillCreate, session: SessionDep, _: AdminUser) -> SkillRead:
    return SkillRead.model_validate(await SkillService(session).create(payload))


