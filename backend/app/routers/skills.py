# --- per-skill graph views -------------------------------------------------
@router.get(
    "/{skill_id}/prerequisites",
    response_model=list[PrerequisiteEdgeRead],
    summary="Direct prerequisites of a skill (what it requires)",
)
async def list_prerequisites(
    skill_id: uuid.UUID,
    session: SessionDep,
    _: CurrentUser,
) -> list[PrerequisiteEdgeRead]:
    edges = await SkillGraphService(session).get_prerequisites(skill_id)
    return [PrerequisiteEdgeRead.model_validate(e) for e in edges]


@router.get(
    "/{skill_id}/dependents",
    response_model=list[DependentEdgeRead],
    summary="Skills that directly require this one",
)
async def list_dependents(
    skill_id: uuid.UUID, session: SessionDep, _: CurrentUser
) -> list[DependentEdgeRead]:
    edges = await SkillGraphService(session).get_dependents(skill_id)
    return [DependentEdgeRead.model_validate(e) for e in edges]


@router.get(
    "/{skill_id}/dependencies",
    response_model=SkillDependencyAnalysis,
    summary="Full dependency analysis: closure, critical path, levels, sequence",
)
async def calculate_dependencies(
    skill_id: uuid.UUID, session: SessionDep, _: CurrentUser
) -> SkillDependencyAnalysis:
    return await SkillGraphService(session).calculate_skill_dependencies(skill_id)


@router.get(
    "/{skill_id}/prerequisite-tree",
    response_model=PrerequisiteTreeResponse,
    summary="Nested prerequisite tree (shared sub-trees expanded once)",
)
async def prerequisite_tree(
    skill_id: uuid.UUID,
    session: SessionDep,
    _: CurrentUser,
    max_depth: int = Query(default=12, ge=1, le=12),
) -> PrerequisiteTreeResponse:
    return await SkillGraphService(session).get_prerequisite_tree(skill_id, max_depth=max_depth)


@router.get(
    "/{skill_id}/graph",
    response_model=SkillGraphResponse,
    summary="Transitive prerequisite closure as a flat node/edge list",
)
async def skill_graph(
    skill_id: uuid.UUID,
    session: SessionDep,
    _: CurrentUser,
    depth: int = Query(default=16, ge=1, le=32),
) -> SkillGraphResponse:
    return await SkillGraphService(session).closure_graph(skill_id, depth)


@router.post(
    "/{skill_id}/prerequisites",
    response_model=PrerequisiteRead,
    status_code=status.HTTP_201_CREATED,
    summary="Add a prerequisite edge (rejected if it would create a cycle)",
)
async def add_prerequisite(
    skill_id: uuid.UUID, payload: PrerequisiteCreate, session: SessionDep, _: AdminUser
) -> PrerequisiteRead:
    edge = await SkillGraphService(session).add_prerequisite(
        payload.model_copy(update={"source_skill_id": skill_id})
    )
    return PrerequisiteRead.model_validate(edge)


# --- prerequisite edge mutation --------------------------------------------
@prerequisites_router.patch("/{edge_id}", response_model=PrerequisiteRead)
async def update_prerequisite(
    edge_id: uuid.UUID, payload: PrerequisiteUpdate, session: SessionDep, _: AdminUser
) -> PrerequisiteRead:
    edge = await SkillGraphService(session).update_prerequisite(edge_id, payload)
    return PrerequisiteRead.model_validate(edge)


@prerequisites_router.delete(
    "/{edge_id}", status_code=status.HTTP_204_NO_CONTENT, response_model=None
)
async def delete_prerequisite(edge_id: uuid.UUID, session: SessionDep, _: AdminUser) -> None:
    await SkillGraphService(session).delete_prerequisite(edge_id)
